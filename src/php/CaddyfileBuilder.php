<?php
declare(strict_types=1);

namespace CaddyPanel;

final class CaddyfileBuilder
{
    public const HEADER = "# Generated by caddy-panel — 高级修改请使用高级/自定义模式\n";

    /** 拼接模式（自包含载荷；适合远程 Admin API、Caddy 无法读取本地片段文件的场景） */
    public static function assemble(string $global, array $fragments): string
    {
        $parts = [self::HEADER];
        $g = trim($global);
        if ($g !== '') {
            $parts[] = $g;
        }
        foreach ($fragments as $f) {
            $f = trim($f);
            if ($f !== '') {
                $parts[] = $f;
            }
        }
        return implode("\n\n", $parts) . "\n";
    }

    /** caddy.d / import 模式：主文件通过 import 引入片段目录（默认绝对路径，适配 API 与磁盘两种加载语义） */
    public static function assembleImport(string $global, string $fragmentsDir): string
    {
        $dir = self::normalizeDir($fragmentsDir);
        $parts = [self::HEADER];
        $g = trim($global);
        if ($g !== '') {
            $parts[] = $g;
        }
        if (glob($dir . '/*.caddy') ?: []) {
            $parts[] = 'import "' . $dir . '/*.caddy"';
        }
        return implode("\n\n", $parts) . "\n";
    }

    private static function normalizeDir(string $dir): string
    {
        $dir = rtrim($dir, '/\\');
        if ($dir === '' || !self::isAbsolute($dir)) {
            $dir = APP_ROOT . '/' . ltrim($dir, '/\\');
        }
        return str_replace('\\', '/', $dir);
    }

    private static function isAbsolute(string $path): bool
    {
        return str_starts_with($path, '/')
            || preg_match('/^[A-Za-z]:[\/\\\\]/', $path) === 1
            || str_starts_with($path, '\\\\');
    }
}
